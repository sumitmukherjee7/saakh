def availability(doc: str, facts: dict, ctx: dict) -> str:
    """How can this applicant obtain `doc`?  ctx: consents granted / analysis flags."""
    if doc in ("aadhaar_ekyc", "pan"):
        return "auto" if ctx.get("ekyc") else "upload"
    if doc == "bank_statement":
        return "auto" if ctx.get("bank_statement") else "upload"
    if doc in ("cashflow_statement", "project_report", "application_form"):
        return "generated" if ctx.get("bank_statement") else "unavailable"
    if doc == "rural_proof":
        return "generated" if facts.get("area_type") == "rural" else "unavailable"
    if doc == "bureau_report":
        return "auto" if ctx.get("bureau") else "offline"
    if doc == "udyam_cert":
        return "auto" if facts.get("udyam_registered") else "unavailable"
    if doc == "gst_cert":
        return "auto" if facts.get("has_gst") else "unavailable"
    if doc == "itr":
        return "auto" if facts.get("has_itr") else "unavailable"
    if doc == "ca_project_report":
        return "paid"
    if doc == "caste_certificate":
        return "upload" if facts.get("social_category") in ("sc", "st", "obc") else "unavailable"
    if doc in ("selfie", "shg_resolution"):
        return "capture"
    if doc == "csc_registration":
        return "offline"
    if doc == "lor":
        return "auto" if facts.get("has_vending_certificate_or_lor") else "unavailable"
    if doc == "animal_proof":
        return "auto" if ctx.get("milk_union_seen") else "unavailable"
    if doc == "vet_certificate":
        return "offline"
    if doc == "shg_grading":
        return "upload" if facts.get("shg_grading_passed") else "unavailable"
    if doc == "edp_certificate":
        return "offline"
    return "upload"  # quotations, utility bill, rent agreement


def plan(facts: dict, schemes: list[str], ctx: dict, uploaded: set[str] | None = None) -> dict[str, Any]:
    uploaded = uploaded or set()
    reqs: list[tuple[str, str, dict, list[str]]] = [("lender", k, lab, alts) for k, (lab, alts) in BASE_REQ.items()]
    for s in schemes:
        for k, (lab, alts) in SCHEME_REQ.get(s, {}).items():
            reqs.append((s, k, lab, alts))
    avail = {d: ("done" if d in uploaded else availability(d, facts, ctx)) for d in DOCS}
    cost = {d: (0.0 if a == "done" else COST[a]) for d, a in avail.items()}

    best = {"cost": float("inf"), "set": None}

    def rec(i: int, chosen: frozenset, c: float):
        if c >= best["cost"]:
            return
        if i == len(reqs):
            best["cost"], best["set"] = c, chosen
            return
        alts = reqs[i][3]
        if any(a in chosen for a in alts):
            rec(i + 1, chosen, c)
            return
        for a in sorted(alts, key=lambda d: cost[d]):
            if cost[a] >= COST["unavailable"]:
                continue
            rec(i + 1, chosen | {a}, c + cost[a])

    rec(0, frozenset(), 0.0)
    chosen = best["set"] or frozenset()
    items = []
    for d in sorted(chosen, key=lambda d: (cost[d], d)):
        serves = [{"scheme": s, "req": k, "label": lab} for s, k, lab, alts in reqs if d in alts]
        items.append({"doc": d, "label": DOCS[d]["label"], "via": DOCS[d]["via"], "how": avail[d],
                      "effort": cost[d], "serves": serves,
                      "post_sanction": d == "edp_certificate",
                      "status": "ready" if avail[d] in ("auto", "generated", "done") else "pending"})
    unmet = [{"scheme": s, "req": k, "label": lab} for s, k, lab, alts in reqs if not any(a in chosen for a in alts)]
    pre = [i for i in items if not i["post_sanction"]]
    ready = sum(1 for i in pre if i["status"] == "ready")
    return {
        "items": items, "unmet": unmet, "total_effort": best["cost"] if best["set"] is not None else None,
        "completeness": round(ready / max(len(pre), 1), 3),
        "counts": {"auto": sum(1 for i in items if i["how"] == "auto"),
                   "generated": sum(1 for i in items if i["how"] == "generated"),
                   "you_do": sum(1 for i in items if i["status"] == "pending"),
                   "total": len(items)},
        "traditional": {"items": TRADITIONAL, "count": len(TRADITIONAL),
                        "note": {"en": "Typical paper checklist at a branch, a field-research hypothesis to validate.",
                                 "hi": "शाखा की सामान्य काग़ज़ी सूची, फ़ील्ड रिसर्च से सत्यापित की जाने वाली परिकल्पना।"}},
    }
