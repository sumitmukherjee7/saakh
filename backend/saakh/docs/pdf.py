"""PDF generation: Detailed Project Report (for the entrepreneur / DIC) and
Credit Memo (for the branch manager). Built from the case state only, every
number traces back to the statement analysis, the scorecard or a cited rule."""
from __future__ import annotations

import io
from datetime import date

from reportlab.graphics.charts.barcharts import VerticalBarChart
from reportlab.graphics.shapes import Drawing, String
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INK = colors.HexColor("#1f2933")
ACCENT = colors.HexColor("#0f766e")
MUTED = colors.HexColor("#6b7280")
LINE = colors.HexColor("#d1d5db")


def rs(x) -> str:
    if x is None:
        return "-"
    n = int(round(float(x)))
    s = str(abs(n))
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts) + "," + tail
    return ("-Rs " if n < 0 else "Rs ") + s


def _styles():
    ss = getSampleStyleSheet()
    return {
        "h1": ParagraphStyle("h1", parent=ss["Title"], fontSize=18, textColor=INK, alignment=0, spaceAfter=4),
        "h2": ParagraphStyle("h2", parent=ss["Heading2"], fontSize=12, textColor=ACCENT, spaceBefore=10, spaceAfter=4),
        "p": ParagraphStyle("p", parent=ss["BodyText"], fontSize=9, leading=12.5, textColor=INK),
        "small": ParagraphStyle("s", parent=ss["BodyText"], fontSize=7.5, leading=10, textColor=MUTED),
    }


def _table(rows, widths, header=True):
    t = Table(rows, colWidths=widths)
    st = [("FONT", (0, 0), (-1, -1), "Helvetica", 8.5), ("TEXTCOLOR", (0, 0), (-1, -1), INK),
          ("LINEBELOW", (0, 0), (-1, -1), 0.3, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
          ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]
    if header:
        st += [("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 8.5), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f0fdfa"))]
    t.setStyle(TableStyle(st))
    return t


def _bar(values, labels, title, w=170 * mm, h=55 * mm):
    d = Drawing(w, h)
    c = VerticalBarChart()
    c.x, c.y, c.width, c.height = 30, 18, w - 40, h - 35
    c.data = [[max(0, v) for v in values]]
    c.categoryAxis.categoryNames = labels
    c.categoryAxis.labels.fontSize = 6.5
    c.valueAxis.labels.fontSize = 6.5
    c.valueAxis.valueMin = 0
    c.bars[0].fillColor = ACCENT
    c.bars[0].strokeColor = None
    d.add(c)
    d.add(String(30, h - 10, title, fontSize=8, fillColor=INK))
    return d


def _mlabel(mk: str) -> str:
    return ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"][int(mk[5:7]) - 1] + mk[2:4]


def _footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 7)
    canvas.setFillColor(MUTED)
    canvas.drawString(15 * mm, 10 * mm, "Generated by Saakh (prototype). Data integrations are SIMULATED. "
                                        "Indicative figures; lender's sanction letter and KFS are binding.")
    canvas.drawRightString(195 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def project_report(case: dict) -> bytes:
    S = _styles()
    f = case["facts"]
    an = case["analysis"]
    offer = case.get("selected_offer") or (case.get("offers") or [{}])[0]
    proj = case.get("project") or {}
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=18 * mm)
    el = [Paragraph("Detailed Project Report", S["h1"]),
          Paragraph(f"{f.get('business_name') or f.get('name')} &middot; {f.get('district')}, {f.get('state')} &middot; prepared {date.today():%d %b %Y}", S["small"]),
          Paragraph("1. Promoter & business", S["h2"])]
    rows = [["Promoter", f.get("name", "-")], ["Activity", str(f.get("activity", "-")).replace("_", " ").title()],
            ["Sector", str(f.get("sector", "-")).replace("_", " ").title()], ["Constitution", str(f.get("ownership_type", "-")).title()],
            ["Years in business", str(f.get("years_in_business", "-"))], ["Location", f"{f.get('district')} ({f.get('area_type')})"],
            ["Udyam", "Registered" if f.get("udyam_registered") else "Not registered"]]
    el.append(_table(rows, [50 * mm, 120 * mm], header=False))
    el.append(Paragraph("2. Project cost", S["h2"]))
    items = proj.get("items", [])
    total = sum(v for _, v in items) or f.get("project_cost") or 0
    el.append(_table([["Item", "Cost"]] + [[k, rs(v)] for k, v in items] + [["Total project cost", rs(total)]], [130 * mm, 40 * mm]))
    el.append(Paragraph("3. Means of finance", S["h2"]))
    loan = offer.get("amount") or 0
    subsidy = offer.get("subsidy") or 0
    own = max(0, total - loan)
    el.append(_table([["Source", "Amount"], [f"Loan, {offer.get('scheme_short', '-')}", rs(loan)],
                      ["Own contribution", rs(own)], ["Capital subsidy (credited to loan account)", rs(subsidy)]],
                     [130 * mm, 40 * mm]))
    meta = (case.get("data") or {}).get("statement") or {}
    nm = an["data_quality"]["months"]
    src = "entrepreneur-uploaded statement (CSV)" if meta.get("source") == "upload" else "Account Aggregator fetch (SIMULATED in this demo)"
    el.append(Paragraph(f"4. Basis: {nm} months of consented bank-statement data ({an['data_quality']['first']} to "
                        f"{an['data_quality']['last']}, {src})", S["h2"]))
    if nm < 12:
        el.append(Paragraph(f"Only {nm} months are available: annual figures are scaled up and seasonality is not observed for a "
                            "full year. The lender should treat projections as indicative.", S["small"]))
    m = an["monthly"]
    el.append(_bar([v / 1000 for v in m["biz_in"]], [_mlabel(x) for x in m["months"]], "Business inflows (Rs '000) by month"))
    bi = sum(m["biz_in"])
    bo = sum(m["biz_out"])
    up = (proj.get("uplift") or 0)
    el.append(Paragraph("5. Projections (3 years)", S["h2"]))
    rows = [["", "Year 1", "Year 2", "Year 3"]]
    rev = [bi * (1 + up * k) for k in (0.7, 1.0, 1.05)]
    cost = [r * bo / max(bi, 1) for r in rev]
    inst = (offer.get("schedule") or [])
    debt = [sum(inst[i * 12:(i + 1) * 12]) for i in range(3)]
    gross = [r - c for r, c in zip(rev, cost)]
    rows += [["Revenue", *[rs(x) for x in rev]], ["Direct costs", *[rs(x) for x in cost]],
             ["Gross margin", *[rs(x) for x in gross]], ["Loan repayment", *[rs(x) for x in debt]],
             ["Debt-service coverage (gross margin / repayment)", *[(f"{g / d:.2f}x" if d else "-") for g, d in zip(gross, debt)]]]
    el.append(_table(rows, [70 * mm, 33 * mm, 33 * mm, 34 * mm]))
    el.append(Paragraph(f"Assumptions: revenue uplift from the financed asset {int(up * 100)}% at full capacity (70% in year 1); "
                        f"cost ratio held at the observed {nm}-month level; repayment per the selected season-matched schedule.", S["small"]))
    doc.build(el, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()


def credit_memo(case: dict, application: dict) -> bytes:
    S = _styles()
    f = case["facts"]
    sc = case.get("score") or {}
    offer = case.get("selected_offer") or {}
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=18 * mm)
    el = [Paragraph("Credit Memo; Saakh pre-appraisal", S["h1"]),
          Paragraph(f"Application {application['id']} &middot; {application['lender']['name']} &middot; file hash {application['hash'][:16]}…", S["small"])]
    el.append(Paragraph("Recommendation (decision support; the branch decides)", S["h2"]))
    el.append(_table([["Requested", "Recommended", "Scheme", "Sim. risk*", "Band", "Schedule"],
                      [rs(offer.get("requested")), rs(offer.get("amount")), offer.get("scheme_short", "-"),
                       f"{sc.get('pd', 0) * 100:.1f}% ({sc.get('pd_low', 0) * 100:.1f}–{sc.get('pd_high', 0) * 100:.1f}%)",
                       sc.get("band", "-"), offer.get("schedule_type", "-")]],
                     [28 * mm, 28 * mm, 30 * mm, 38 * mm, 14 * mm, 32 * mm]))
    el.append(Paragraph("* Simulated risk estimate from a scorecard trained on synthetic data, not a validated probability of "
                        "default. The model's fairness release gate is currently BLOCKED (see Governance); demonstration only.", S["small"]))
    el.append(Paragraph("Scorecard contributions", S["h2"]))
    rows = [["Factor", "Applicant value", "Bin", "Points", "Max"]]
    for c in sc.get("contributions", []):
        rows.append([c["label"]["en"], c["display"], c["bin"], f"{c['points']:.0f}", f"{c['max_points']:.0f}"])
    el.append(_table(rows, [70 * mm, 28 * mm, 40 * mm, 16 * mm, 16 * mm]))
    if sc.get("reason_codes"):
        el.append(Paragraph("Principal reasons for points lost: " + "; ".join(r["label"]["en"] for r in sc["reason_codes"]), S["p"]))
    el.append(Paragraph("Scheme eligibility (rule engine, cited)", S["h2"]))
    rows = [["Scheme", "Status", "Basis"]]
    for r in case.get("schemes", []):
        basis = "; ".join(f"{fl['text']['en']} [{fl['cite']['source']}]" for fl in r["failing"][:2]) if r["failing"] else \
            f"{len(r['citations'])} cited criteria met"
        rows.append([r["short"], r["eligibility"].replace("_", " "), Paragraph(basis, S["small"])])
    el.append(_table(rows, [35 * mm, 25 * mm, 110 * mm]))
    el.append(Paragraph("Documents", S["h2"]))
    docs = case.get("documents") or {}
    rows = [["Document", "Obtained via", "Status"]]
    for d in docs.get("items", []):
        rows.append([d["label"]["en"], d["via"], d["status"]])
    el.append(_table(rows, [80 * mm, 55 * mm, 35 * mm]))
    el.append(Paragraph("Consent & integrity", S["h2"]))
    rows = [["Consent", "Status", "Purpose"]]
    for c in application.get("consents", []):
        rows.append([c["kind"], c["status"], Paragraph(c["purpose"]["text"]["en"], S["small"])])
    el.append(_table(rows, [40 * mm, 25 * mm, 105 * mm]))
    el.append(Paragraph(f"Entrepreneur approval recorded {application['approval']['ts']} bound to file hash "
                        f"{application['hash']}. Audit chain head {application.get('audit_head', '-')}.", S["small"]))
    doc.build(el, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
